#!/usr/bin/env python3
"""
Typical real sizes per sand3d entry label, for src/realscale.ts.

Reads every object's label (public/museum/t/<shard>.json) and its measured raw size
(public/museum/s/<shard>.json, the same order) and writes src/realsize-labels.ts:

  LABEL_RANGE[label] = for broad labels (n >= 10), their 10th-90th percentile when wider than the tolerance
  LABEL[label]  = typical largest dimension (m): the median over all objects with that label
                  (n >= 3; most sand3d programs are modelled at real size, and the CAD/Articraft/
                  SimReady/AutoMate sets always are), so a few wrongly-scaled sources don't move it
  FAMILY[family] = plausible [min, max] largest dimension: 2nd-98th percentile over objects that
                  sit within 2.5x of their label's typical size

Prints labels whose median disagrees with the hand-written SIZE table in realscale.ts by > 3x
(the label table wins for entry labels, SIZE for title words: check those).

    python3 scripts/build_realsize.py
"""
import collections, glob, json, math, os, re, statistics

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
rows = []
for tf in sorted(glob.glob(f'{ROOT}/public/museum/t/*.json')):
    t = json.load(open(tf))
    s = json.load(open(tf.replace('/t/', '/s/')))
    for k, lst in t.items():
        for r, sz in zip(lst, s.get(k, [])):
            if sz and max(sz) > 0:
                rows.append((r[0], r[4], r[5], max(sz)))

lab = collections.defaultdict(list)
for ds, fam, e, m in rows:
    if e:
        lab[e].append(math.log10(m))
LABEL = {e: 10 ** statistics.median(v) for e, v in lab.items() if len(v) >= 3}
# broad labels ('tower': a 1 m model or a 100 m building) keep their measured 10th-90th percentile
# as plausible too, so only the clearly wrong tails are corrected
SPREAD = {}
for e, v in lab.items():
    if len(v) >= 10:
        v = sorted(v)
        lo, hi = 10 ** v[len(v) // 10], 10 ** v[(9 * len(v)) // 10]
        if lo < LABEL[e] / 2.5 or hi > LABEL[e] * 2.5:
            SPREAD[e] = [min(lo, LABEL[e] / 2.5), max(hi, LABEL[e] * 2.5)]

TOL = math.log10(2.5)
fam_sizes = collections.defaultdict(list)
for ds, fam, e, m in rows:
    if ds == 'objaverse' and e in LABEL and abs(math.log10(m / LABEL[e])) <= TOL and fam and not fam.isdigit():
        fam_sizes[fam].append(m)
FAMILY = {}
for f, v in fam_sizes.items():
    v.sort()
    FAMILY[f] = [v[int(len(v) * 0.02)], v[min(len(v) - 1, int(len(v) * 0.98))]]

# compare with the hand-written table
src = open(f'{ROOT}/src/realscale.ts').read()
body = src[src.index('const SIZE'):src.index('};', src.index('const SIZE'))]
hand = {k: float(v) for k, v in re.findall(r'(\w+): ([\d.]+)', body)}
odd = [(e, round(LABEL[e], 3), hand[e], len(lab[e])) for e in LABEL if e in hand and abs(math.log10(LABEL[e] / hand[e])) > math.log10(3)]
print(f'{len(rows)} objects, {len(SPREAD)} broad labels, {len(LABEL)} labels with n >= 3 (cover {sum(len(lab[e]) for e in LABEL)} objects)')
print('hand SIZE vs label median > 3x apart (the label table wins for entry labels; SIZE is used for title words):', odd)

sig = lambda x: float(f'{x:.3g}')
with open(f'{ROOT}/src/realsize-labels.ts', 'w') as f:
    f.write('// Generated by scripts/build_realsize.py from public/museum/{t,s} (do not edit by hand).\n')
    f.write('/** typical largest dimension (m) per sand3d entry label: median over the objects with that label (n >= 3) */\n')
    f.write('export const LABEL: Record<string, number> = ' + json.dumps({e: sig(v) for e, v in sorted(LABEL.items())}, separators=(',', ':')) + ';\n')
    f.write('/** broad labels: plausible [min, max] largest dimension (m), the 10th-90th percentile of their objects when wider than the default tolerance */\n')
    f.write('export const LABEL_RANGE: Record<string, [number, number]> = ' + json.dumps({e: [sig(a), sig(b)] for e, (a, b) in sorted(SPREAD.items())}, separators=(',', ':')) + ';\n')
    f.write('/** plausible [min, max] largest dimension (m) per family: 2nd-98th percentile of well-scaled objects */\n')
    f.write('export const FAMILY_RANGE: Record<string, [number, number]> = ' + json.dumps({k: [sig(a), sig(b)] for k, (a, b) in sorted(FAMILY.items())}, separators=(',', ':')) + ';\n')
print('wrote src/realsize-labels.ts', os.path.getsize(f'{ROOT}/src/realsize-labels.ts'), 'bytes')
print({k: [round(a, 3), round(b, 2)] for k, (a, b) in sorted(FAMILY.items())})
